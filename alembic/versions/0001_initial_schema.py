"""Initial schema (all 20 tables) plus PostgreSQL hardening.

The base schema is created from the model metadata so the migration can never drift from the models
at this first revision. Every later change MUST be a new autogenerated revision
(`alembic revision --autogenerate -m "..."`).

PostgreSQL extras: a GIN full-text index on documents.search_text and triggers that reject UPDATE/DELETE
on append-only tables (audit_logs, document_versions, approval_history) even for direct SQL access.
"""
from alembic import op

import app.models  # noqa: F401
from app.db.base import Base

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None

APPEND_ONLY = ("audit_logs", "document_versions", "approval_history")


def upgrade() -> None:
    bind = op.get_bind()
    Base.metadata.create_all(bind)
    if bind.dialect.name == "postgresql":
        op.execute("CREATE INDEX IF NOT EXISTS ix_documents_search_fts ON documents "
                   "USING gin (to_tsvector('english', coalesce(search_text, '')))")
        op.execute("""CREATE OR REPLACE FUNCTION forbid_mutation() RETURNS trigger AS $$
                      BEGIN RAISE EXCEPTION '% is append-only', TG_TABLE_NAME; END; $$ LANGUAGE plpgsql""")
        for table in APPEND_ONLY:
            op.execute(f"CREATE TRIGGER trg_{table}_immutable BEFORE UPDATE OR DELETE ON {table} "
                       f"FOR EACH ROW EXECUTE FUNCTION forbid_mutation()")


def downgrade() -> None:
    bind = op.get_bind()
    if bind.dialect.name == "postgresql":
        for table in APPEND_ONLY:
            op.execute(f"DROP TRIGGER IF EXISTS trg_{table}_immutable ON {table}")
        op.execute("DROP FUNCTION IF EXISTS forbid_mutation()")
    Base.metadata.drop_all(bind)
